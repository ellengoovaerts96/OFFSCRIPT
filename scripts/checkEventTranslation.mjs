import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import vm from 'node:vm';
import * as zod from 'zod';
import * as formats from 'openai/helpers/zod';
import * as crypto from 'node:crypto';
import { emptyEvent } from '../src/logic/eventImport.ts';
import { formatPublishedEventMessages } from '../src/logic/publishedEvents.ts';
let calls=0,available=true,broken=false,fail=false,lastRequest;
const translated={index:0,title:'Schilderworkshop en livemuziek',description:'Schilderen bij Boma met livemuziek.',price:'10500 F',conditions:'Consumptie verplicht'};
const api={hasOpenAIKey:()=>available,openaiModel:'test',getOpenAIClient:options=>{
  assert.equal(options.maxRetries,0);assert.equal(options.timeoutMs,4500);
  return {responses:{parse:async input=>{calls++;lastRequest=input;if(fail)throw new Error('Timeout');return {output_parsed:{events:[{...translated,price:broken?'Gratis':'10500 F'}]}}}}};
}};
const module=new vm.SourceTextModule(stripTypeScriptTypes(await readFile(new URL('../src/ai/localizeEventText.ts',import.meta.url),'utf8')));
await module.link(async name=>{
  const values=name==='node:crypto'?crypto:name==='zod'?zod:name.includes('helpers/zod')?formats:api;
  return new vm.SyntheticModule(Object.keys(values),function(){for(const [key,value] of Object.entries(values))this.setExport(key,value)});
});
await module.evaluate();
const {localizeEventText}=module.namespace;
const event={...emptyEvent(),title:'Des ateliers de peinture & musique live',description:'Painting at Boma with live music.',venueName:'Boma',eventDate:'2026-09-24',startTime:'20:00',price:'10500 F',conditions:'Consommation obligatoire',googleMapsUrl:'https://maps.app.goo.gl/test',contactPhone:'+221773738411'};
const result=await localizeEventText([event],'nl');
assert.equal(result.unavailable,false);assert.equal(result.events[0].title,translated.title);
for(const key of ['venueName','eventDate','startTime','googleMapsUrl','contactPhone'])assert.equal(result.events[0][key],event[key]);
assert.equal(event.title,'Des ateliers de peinture & musique live');
assert.ok(lastRequest.instructions.includes('Dutch'));
const message=formatPublishedEventMessages(result.events,'nl')[0];
assert.ok(message.includes('donderdag 24 september 2026'));assert.ok(message.includes('Consumptie verplicht'));assert.ok(message.includes('https://wa.me/221773738411'));
await localizeEventText([event],'nl');assert.equal(calls,1);
broken=true;
assert.equal((await localizeEventText([{...event,title:'Other title'}],'nl')).unavailable,true);
broken=false;fail=true;
assert.equal((await localizeEventText([event],'fr')).unavailable,true);
fail=false;available=false;
const fallback=await localizeEventText([event],'de');assert.equal(fallback.unavailable,true);assert.equal(fallback.events[0].conditions,event.conditions);
assert.ok(formatPublishedEventMessages(fallback.events,'de',true)[0].includes('Originaltext'));
console.log('Event translation: Dutch prose, stable facts, caching, amount validation and safe fallback passed.');
